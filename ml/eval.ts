import fs from "node:fs";
import path from "node:path";
import { FORECAST_MODEL } from "../shared/forecastModel";
import { makeEpisodes, type Episode } from "./episodes";
import { aiDetector, linearTrend, summarize, thresholdCritical, thresholdWarning, type Detector, type Summary } from "./metrics";
import { HORIZON } from "../shared/forecast";

/**
 * HELD-OUT TEST: episodes the model never saw (seeds 900000+; training used 1..N and validation 100000..).
 *   npm run ml:eval        -> prints the tables and writes ml/RESULTS.md
 * Three test sets: the Factory template, the Cold-storage template (new random settings and incidents), and brand-new random
 * floor plans (different zones, sizes and limits than anything in the app's templates).
 */
const N = Number(process.env.ML_TEST_EPISODES) || 200;
const SETS: { name: string; eps: () => Episode[] }[] = [
  { name: "Factory template, new incidents", eps: () => makeEpisodes(900_000, N, "factory") },
  { name: "Cold-storage template, new incidents", eps: () => makeEpisodes(910_000, N, "cold") },
  { name: "Unseen random floor plans", eps: () => makeEpisodes(920_000, N * 2, "random") },
];
const DETECTORS: { name: string; det: Detector }[] = [
  { name: "Threshold alarm (critical limit only)", det: thresholdCritical },
  { name: "Threshold + warning margin (the app's warning level)", det: thresholdWarning },
  { name: "Straight-line trend (simple, no ML)", det: linearTrend },
  { name: "AI model (trained neural network)", det: aiDetector(FORECAST_MODEL) },
];

const pct = (v: number) => `${(100 * v).toFixed(0)}%`;
function table(rows: { name: string; s: Summary }[]): string {
  const head = "| Detector | Warned before breach | Median lead (all breaches) | Median lead (when warned) | False alarms / 100 zone-runs |\n|---|---|---|---|---|";
  return [head, ...rows.map(({ name, s }) => `| ${name} | ${pct(s.earlyRate)} (${s.early}/${s.events}) | ${s.medianLead} steps | ${s.medianLeadWhenEarly} steps | ${s.falseAlarmsPer100.toFixed(1)} |`)].join("\n");
}

const marginScaled = (scale: number): Detector => (ep, zi) => {
  const z = ep.zones[zi], w = z.warnMarginC * scale;
  let on = false;
  return ep.seen[zi].map((r) => {
    const m = Math.min(z.maxC - r.max, r.min - z.minC);
    if (m < w) on = true; else if (m >= w + 0.3) on = false;
    return on;
  });
};

let md = `# Held-out results\n\nGenerated by \`npm run ml:eval\` on ${new Date().toISOString().slice(0, 10)}. Model: ${FORECAST_MODEL.meta.network}, trained on ${FORECAST_MODEL.meta.trainEpisodes} simulated episodes, alarm threshold ${FORECAST_MODEL.alarm.threshold}.\n\n` +
  `**How to read this.** One *simulation step* is one second at demo speed. "Warned before breach" = the alarm was already on the step before a zone really went out of range. ` +
  `A *breach* is a zone truly out of its limits (noise-free). A *false alarm* is an alarm with no breach in the next ${HORIZON} steps. ` +
  `Every detector only sees noisy readings (sensor noise up to 0.2 °C). Lead times are capped at 90 steps. The "zone-run" is one zone for one 360-step episode. ` +
  `Many incidents (a fire starting, a door left open) go from normal to out-of-range within a few steps, with no earlier sign in the readings, so no method can warn ahead of those. ` +
  `The AI's value is on incidents that develop over time.\n`;
const all: Episode[] = [];
for (const set of SETS) {
  const eps = set.eps();
  all.push(...eps);
  const rows = DETECTORS.map((d) => ({ name: d.name, s: summarize(eps, d.det) }));
  const t = table(rows);
  console.log(`\n=== ${set.name}: ${eps.length} episodes, ${rows[0].s.zoneEpisodes} zone-runs, ${rows[0].s.events} breaches ===\n${t}`);
  md += `\n## ${set.name}\n\n${eps.length} episodes, ${rows[0].s.zoneEpisodes} zone-runs, ${rows[0].s.events} real breaches.\n\n${t}\n`;
}

// Fair comparison: the margin alarm is noisy by nature (it fires whenever a zone sits near a limit). Shrink its margin until its
// false-alarm rate is no higher than the AI's, then compare how early each one warns.
const ai = summarize(all, aiDetector(FORECAST_MODEL));
let scale = 0;
for (let sc = 1; sc >= 0; sc = Math.round((sc - 0.05) * 100) / 100) if (summarize(all, marginScaled(sc)).falseAlarmsPer100 <= ai.falseAlarmsPer100) { scale = sc; break; }
const matched = marginScaled(scale);
const pooled = [
  { name: "Threshold alarm (critical limit only)", s: summarize(all, thresholdCritical) },
  { name: `Margin alarm tuned to the same false-alarm rate (margin x ${scale})`, s: summarize(all, matched) },
  { name: "AI model (trained neural network)", s: ai },
];
const pt = table(pooled);
console.log(`\n=== ALL TEST SETS POOLED, false alarms matched: ${ai.zoneEpisodes} zone-runs, ${ai.events} breaches ===\n${pt}`);
md += `\n## All test sets pooled, false alarms matched\n\n${ai.zoneEpisodes} zone-runs, ${ai.events} breaches. The margin alarm's margin was shrunk (x ${scale}) until it raises no more false alarms than the AI, so the question is only: who warns earlier?\n\n${pt}\n`;

const kinds = ["cooling-failure", "overheat", "door-open", "fire", "normal"] as const;
const head = "| Incident | Breaches | Threshold: warned early | Matched margin: warned early (lead) | AI: warned early (lead) |\n|---|---|---|---|---|";
const lines = kinds.map((k) => {
  const sub = all.filter((e) => e.incident === k);
  const a = summarize(sub, thresholdCritical), b = summarize(sub, matched), c = summarize(sub, aiDetector(FORECAST_MODEL));
  return `| ${k} | ${c.events} | ${pct(a.earlyRate)} | ${pct(b.earlyRate)} (${b.medianLeadWhenEarly} steps) | ${pct(c.earlyRate)} (${c.medianLeadWhenEarly} steps) |`;
});
console.log(`\n=== BY INCIDENT TYPE ===\n${[head, ...lines].join("\n")}`);
md += `\n## By incident type (pooled)\n\n"normal" = a quiet episode where only brief harmless disturbances happened (some of them still pushed a zone out of range).\n\n${[head, ...lines].join("\n")}\n`;

fs.writeFileSync(path.resolve(__dirname, "RESULTS.md"), md);
console.log("\nwritten ml/RESULTS.md");
